function useScreenTexture(): THREE.CanvasTexture {
    const tex = useMemo(() => {
        const c = document.createElement('canvas');
        c.width = 256; c.height = 160;
        const ctx = c.getContext('2d')!;
        ctx.fillStyle = '#0d1526'; ctx.fillRect(0, 0, 256, 160);
        ctx.fillStyle = '#1c2941'; ctx.fillRect(0, 0, 256, 16);
        ['#ff6b6b', '#f7c948', '#51cf66'].forEach((col, i) => {
            ctx.fillStyle = col;
            ctx.beginPath(); ctx.arc(12 + i * 14, 8, 3.2, 0, Math.PI * 2); ctx.fill();
        });
        const palette = ['#7dd3fc', '#c4b5fd', '#86efac', '#fca5a5', '#fde68a'];
        for (let row = 0, y = 26; y < 152; row++, y += 11) {
            ctx.fillStyle = palette[row % palette.length];
            ctx.fillRect(10 + (row % 4) * 10, y, 28 + ((row * 53) % 130), 5);
        }
        const t = new THREE.CanvasTexture(c);
        t.colorSpace = THREE.SRGBColorSpace;
        return t;
    }, []);
    useEffect(() => () => { tex.dispose(); }, [tex]);
    return tex;
}

