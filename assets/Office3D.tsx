/** Minimal structural type for the OrbitControls instance drei exposes. */
interface OrbitControlsLike {
    target: THREE.Vector3;
    minDistance: number;
    maxDistance: number;
    update: () => void;
}

interface CameraRigProps {
    center: Vec2;
    radius: number;
}

const CameraRig: React.FC<CameraRigProps> = ({ center, radius }) => {
    const get = useThree((s) => s.get);

    useEffect(() => {
        const { camera, controls } = get() as unknown as {
            camera: THREE.PerspectiveCamera;
            controls: OrbitControlsLike | null;
        };

        camera.position.set(
            center[0] + radius * 0.55,
            radius * 0.9 + 1.6,
            center[1] + radius * 1.55 + 2.0
        );

        if (controls) {
            controls.target.set(center[0], 0.9, center[1]);
            controls.minDistance = 2.5;
            controls.maxDistance = radius * 3 + 8;
            controls.update();
        }
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [center[0], center[1], radius, get]);

    return null;
};

