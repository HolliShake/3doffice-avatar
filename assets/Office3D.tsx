const clampNum = (v: number, min: number, max: number): number =>
    Math.min(max, Math.max(min, v));

/* ═══════════════════════════ 6. LAYOUT ENGINE ═════════════════════════════ */

/** Resolve defaults + clamp values. Pure — safe to call in render. */
export function resolveLayout(layout: OfficeLayout = {}): ResolvedOfficeLayout {
    const desks = clampNum(Math.floor(layout.desks ?? 4), 0, 500);
    const desksPerRow =
        layout.desksPerRow === 'auto' || layout.desksPerRow === undefined
            ? Math.max(1, Math.ceil(Math.sqrt(desks)))
            : clampNum(Math.floor(layout.desksPerRow), 1, Math.max(1, desks));
    const deskGap = clampNum(layout.deskGap ?? 2.7, 1, 20);
    const rowGap = clampNum(layout.rowGap ?? 3.1, 1, 20);
    const faceAlternate = layout.faceAlternate ?? false;
    const table = layout.table ?? true;
    const tableSeats = clampNum(Math.floor(layout.tableSeats ?? 4), 1, 12);

    // 'auto': behind the desk grid (row 0 sits closest to the camera, +z)
    const rows = desks > 0 ? Math.ceil(desks / desksPerRow) : 0;
    const minZ = desks > 0 ? -((rows - 1) / 2) * rowGap - 0.5 : 0;
    const tablePosition: Vec2 =
        layout.tablePosition === 'auto' || layout.tablePosition === undefined
            ? [0, minZ - 2.6]
            : [layout.tablePosition[0], layout.tablePosition[1]];

    return { desks, desksPerRow, deskGap, rowGap, faceAlternate, table, tableSeats, tablePosition };
}

/** Defaults for reference / UIs. */
export const DEFAULT_LAYOUT: Readonly<ResolvedOfficeLayout> = resolveLayout();

/**
 * Pure layout → stations resolver. Call it yourself to enumerate ids for your UI.
 * Ids are stable and order-independent: `desk-{index}`, `table-{seatIndex}`.
 */
export function resolveStations(layout: OfficeLayout = {}): StationDef[] {
    const L = resolveLayout(layout);
    const stations: StationDef[] = [];

    for (let i = 0; i < L.desks; i++) {
        const row = Math.floor(i / L.desksPerRow);
        const col = i % L.desksPerRow;
        const inRow = Math.min(L.desksPerRow, L.desks - row * L.desksPerRow);
        const x = (col - (inRow - 1) / 2) * L.deskGap;
        const z = ((rows(L) - 1) / 2 - row) * L.rowGap;
        stations.push({
            kind: 'desk',
            id: `desk-${i}`,
            position: [x, 0, z],
            rotationY: L.faceAlternate && row % 2 === 1 ? Math.PI : 0,
            seat: { position: [0, 0, -0.45], rotationY: 0 },
            hoverRadius: 1.5,
        });
    }

    if (L.table) {
        const [tx, tz] = L.tablePosition;
        stations.push({
            kind: 'table',
            id: 'table',
            position: [tx, 0, tz],
            hoverRadius: 1.6,
            seats: Array.from({ length: L.tableSeats }, (_, k) => {
                const a = (k / L.tableSeats) * Math.PI * 2 + Math.PI / 2;
                return {
                    id: `table-${k}`,
                    position: [Math.sin(a) * 1.2, 0, Math.cos(a) * 1.2],
                    rotationY: a + Math.PI,
                };
            }),
        });
    }
    return stations;

    function rows(l: ResolvedOfficeLayout): number {
        return l.desks > 0 ? Math.ceil(l.desks / l.desksPerRow) : 0;
    }
}

/** All assignable station ids for a set of stations. */
export function stationIds(stations: readonly StationDef[]): StationId[] {
    return stations.flatMap((s) => (s.kind === 'desk' ? [s.id] : s.seats.map((t) => t.id)));
}

