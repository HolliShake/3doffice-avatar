/* ══════════════════════════ 4. RUNTIME VALIDATORS ═════════════════════════ */

/** Type guard for `AvatarConfig` (e.g. before trusting API data). */
export const isAvatarConfig = (value: unknown): value is AvatarConfig => {
    if (typeof value !== 'object' || value === null) return false;
    const v = value as Record<string, unknown>;
    const colors = ['skinColor', 'hairColor', 'shirtColor', 'pantsColor', 'shoeColor', 'eyeColor'] as const satisfies readonly (keyof AvatarConfig)[];
    const bools = ['followMouse', 'typing'] as const satisfies readonly (keyof AvatarConfig)[];
    return (
        colors.every((k) => v[k] === undefined || isHexColor(v[k])) &&
        bools.every((k) => v[k] === undefined || typeof v[k] === 'boolean')
    );
};

/** Type guard for `AvatarAssignments` (all values must be valid configs). */
export const isAvatarAssignments = (value: unknown): value is AvatarAssignments =>
    typeof value === 'object' && value !== null && Object.values(value).every(isAvatarConfig);

/** Type guard for `OfficeLayout`. */
export const isOfficeLayout = (value: unknown): value is OfficeLayout => {
    if (typeof value !== 'object' || value === null) return false;
    const v = value as Record<string, unknown>;
    const num = (x: unknown): x is number => typeof x === 'number' && Number.isFinite(x);
    return (
        (v.desks === undefined || (num(v.desks) && v.desks >= 0)) &&
        (v.desksPerRow === undefined || v.desksPerRow === 'auto' || (num(v.desksPerRow) && v.desksPerRow >= 1)) &&
        (v.deskGap === undefined || (num(v.deskGap) && v.deskGap >= 1)) &&
        (v.rowGap === undefined || (num(v.rowGap) && v.rowGap >= 1)) &&
        (v.faceAlternate === undefined || typeof v.faceAlternate === 'boolean') &&
        (v.table === undefined || typeof v.table === 'boolean') &&
        (v.tableSeats === undefined || (num(v.tableSeats) && v.tableSeats >= 1)) &&
        (v.tablePosition === undefined || v.tablePosition === 'auto' ||
            (Array.isArray(v.tablePosition) && v.tablePosition.length === 2 && v.tablePosition.every(num)))
    );
};

