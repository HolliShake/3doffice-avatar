/**
 * Strict CSS hex color — `#rgb` or `#rrggbb`.
 *
 * String literals are validated at compile time:
 *   `const ok:  HexColor = '#ff0044'`  ✅
 *   `const bad: HexColor = 'red'`      ❌ compile error
 *
 * For dynamic strings (API, color picker) use the `hex()` helper below.
 * Prefer lenient typing? Change to: `type HexColor = ` + "`#${string}`" + `.
 */
export type HexColor = `#${string}`;

const HEX_RE = /^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/;

/** Type guard: is this value a valid hex color string? */
export const isHexColor = (value: unknown): value is HexColor =>
    typeof value === 'string' && HEX_RE.test(value);

/** Runtime-validate + cast a dynamic string (API, color picker, …) to `HexColor`. */
export function hex(value: string): HexColor {
    if (!HEX_RE.test(value)) throw new Error(`[Office3D] Invalid hex color: "${value}"`);
    return value as HexColor;
}

/** 3D point `[x, y, z]` in meters. */
export type Vec3 = [x: number, y: number, z: number];
/** 2D ground-plane point `[x, z]` in meters. */
export type Vec2 = [x: number, z: number];

/**
 * Identifier of an assignable seat, generated by `resolveStations()`:
 *   desks → `desk-0`, `desk-1`, … · table → `table-0`, `table-1`, …
 * Typos such as `'desks-0'` or `'desk'` are caught at compile time.
 */
export type StationId = `desk-${number}` | `table-${number}`;

/** Furniture category. */
export type StationKind = 'desk' | 'table';

/** Exhaustiveness helper for discriminated unions. */
export function assertNever(value: never, context = ''): never {
    throw new Error(`[Office3D] Unhandled variant${context ? ` (${context})` : ''}: ${JSON.stringify(value)}`);
}

/* ═════════════════════════════ 2. LAYOUT TYPES ════════════════════════════ */

/**
 * Office layout configuration. All fields optional — omitted fields fall back
 * to their documented default (or `'auto'` where noted).
 */
export interface OfficeLayout {
    /** Number of desk stations, arranged as a centered grid. @default 4 @min 0 */
    desks?: number;
    /**
     * Desks per grid row.
     * - `number` — exact count (clamped to `[1, desks]`)
     * - `'auto'` — `ceil(√desks)`, i.e. a roughly square grid
     * @default 'auto'
     */
    desksPerRow?: number | 'auto';
    /** Horizontal distance between desks, meters. @default 2.7 @min 1 */
    deskGap?: number;
    /** Depth distance between desk rows, meters. @default 3.1 @min 1 */
    rowGap?: number;
    /** Rotate every odd row 180° (back-to-back rows, like an open-plan office). @default false */
    faceAlternate?: boolean;
    /** Render the round meeting table. @default true */
    table?: boolean;
    /** Number of stools (assignable seats) around the table. @default 4 @min 1 @max 12 */
    tableSeats?: number;
    /**
     * Table center `[x, z]` in meters, or `'auto'` to place it behind the desk grid.
     * @default 'auto'
     */
    tablePosition?: Vec2 | 'auto';
}

/** `OfficeLayout` with every field filled in — what the layout engine consumes. */
export interface ResolvedOfficeLayout {
    desks: number;
    desksPerRow: number;
    deskGap: number;
    rowGap: number;
    faceAlternate: boolean;
    table: boolean;
    tableSeats: number;
    tablePosition: Vec2;
}

