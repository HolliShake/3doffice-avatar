interface OfficeSceneProps {
    stations: readonly StationDef[];
    assignments: AvatarAssignments;
    screensOn: boolean;
    controlledLampOn: boolean | undefined;
    defaultLampsOn: boolean;
    onLampToggle?: (id: StationId, on: boolean) => void;
    onStationClick?: (id: StationId) => void;
}

const OfficeScene: React.FC<OfficeSceneProps> = ({
    stations, assignments, screensOn, controlledLampOn, defaultLampsOn, onLampToggle, onStationClick,
}) => {
    const [lampStates, setLampStates] = useState<Partial<Record<StationId, boolean>>>({});
    const getLampOn = (id: StationId): boolean => controlledLampOn ?? lampStates[id] ?? defaultLampsOn;
    const handleLampToggle = (id: StationId) => (next: boolean) => {
        setLampStates((prev) => ({ ...prev, [id]: next }));
        onLampToggle?.(id, next);
    };

    const bounds = useMemo(() => {
        let minX = 0, maxX = 0, minZ = 0, maxZ = 0;
        for (const s of stations) {
            const [x, , z] = s.position;
            const r = s.hoverRadius;
            minX = Math.min(minX, x - r); maxX = Math.max(maxX, x + r);
            minZ = Math.min(minZ, z - r); maxZ = Math.max(maxZ, z + r);
        }
        const center: Vec2 = [(minX + maxX) / 2, (minZ + maxZ) / 2];
        return { center, radius: Math.max(maxX - minX, maxZ - minZ) / 2 + 1 };
    }, [stations]);

    return (
        <>
            <ambientLight intensity={0.85} />
            <directionalLight position={[4, 7, 5]} intensity={1.5} />
            <directionalLight position={[-5, 4, -6]} intensity={0.5} color="#cdd9ff" />

            <mesh rotation={[-Math.PI / 2, 0, 0]}>
                <circleGeometry args={[Math.max(10, bounds.radius * 2.4), 64]} />
                <meshStandardMaterial color="#e6eaf1" roughness={1} />
            </mesh>

            {stations.map((def) => (
                <Station
                    key={def.id}
                    def={def}
                    assignments={assignments}
                    screensOn={screensOn}
                    lampOn={getLampOn(def.kind === 'desk' ? def.id : 'table-0')}
                    onLampToggle={handleLampToggle(def.kind === 'desk' ? def.id : 'table-0')}
                    onStationClick={onStationClick}
                />
            ))}

            <ContactShadows
                position={[0, 0.001, 0]}
                opacity={0.35}
                scale={Math.max(18, bounds.radius * 4)}
                blur={2.4}
                far={3}
                color="#1e293b"
            />
            <OrbitControls makeDefault enablePan={false} maxPolarAngle={Math.PI * 0.49} />
            <CameraRig center={bounds.center} radius={bounds.radius} />
        </>
    );
};

